// Generates pi-adapter/openui-guide.mjs: the text that tells an agent the WebUI renders ```openui
// blocks and which components exist. It comes straight from the component library, so a new or
// changed component can never be missing from what the agent is told. `--check` fails if the
// committed file is stale (used by the test suite).
import { build } from 'esbuild';
import { mkdtemp, readFile, rm, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { generatePrompt } from '@openuidev/react-lang';
import { pathToFileURL, fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const target = path.join(root, 'pi-adapter/openui-guide.mjs');

const PREAMBLE = [
  'The operator reads this conversation in the Hayate WebUI. There, a fenced code block with the language `openui` is not shown as code but rendered as a live interface (cards, key figures, tables, tags).',
  'Use it when a table, a set of figures or a status overview is clearer than prose: write the block with the exact syntax below, and add one short sentence of text around it. Do not use it for ordinary answers. Other clients (terminal, Matrix) show the block as plain code, so never rely on it alone for something the operator must not miss.',
  'Only the components listed below exist; anything else is dropped. The block shows data you write into it; it cannot fetch data or call tools.'
].join('\n\n');

// Chat blocks are data-only: a button click or a query has nothing to talk to there. So the guide is
// generated from the library WITHOUT the interactive components (and thus without the generic
// "Button(...)" / action / query sections), instead of being patched afterwards.
const INTERACTIVE = ['Btn'];

export async function renderGuide() {
  const scratch = await mkdtemp(path.join(root, '.openui-guide-'));
  try {
    const out = path.join(scratch, 'library.mjs');
    await build({ entryPoints: [path.join(root, 'dashboard/public/ui/dashboard/library.jsx')], bundle: true, format: 'esm', platform: 'node',
      outfile: out, jsx: 'automatic', external: ['react', 'react-dom'], logLevel: 'error' });
    const { dashboardLibrary } = await import(pathToFileURL(out).href);
    const spec = dashboardLibrary.toSpec();
    const components = Object.fromEntries(Object.entries(spec.components).filter(([name]) => !INTERACTIVE.includes(name)));
    const guide = generatePrompt({ root: spec.root, components, componentGroups: spec.componentGroups, preamble: PREAMBLE });
    const sha = createHash('sha256').update(guide).digest('hex');
    return `// GENERATED by scripts/openui-guide.mjs from dashboard/public/ui/dashboard/library.jsx. Do not edit; run \`node scripts/openui-guide.mjs\`.\nexport const OPENUI_GUIDE_SHA256 = ${JSON.stringify(sha)};\nexport const OPENUI_GUIDE = ${JSON.stringify(guide)};\n`;
  } finally { await rm(scratch, { recursive: true, force: true }); }
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const text = await renderGuide();
  // `--out <file>` writes a copy for another repository (the Hayate workspace plugin) and checks it with --check.
  const outIndex = process.argv.indexOf('--out');
  const file = outIndex > 0 ? path.resolve(process.argv[outIndex + 1]) : target;
  if (process.argv.includes('--check')) {
    const current = await readFile(file, 'utf8').catch(() => '');
    if (current !== text) { console.error(`${file} is stale: run node scripts/openui-guide.mjs${outIndex > 0 ? ' --out ' + file : ''}`); process.exitCode = 1; }
  } else await writeFile(file, text);
}
